/**
 * The support tables in the countries and languages guide, generated from the
 * same lists and provider declarations the worker runs on so the page can't drift
 * from them.
 */
import { COUNTRIES, countryName, DEFAULT_MARKET, LANGUAGES, languageName } from "@workspace/config/markets";
import { getModelMeta } from "@workspace/config/models";
import { type ModelConfig, parseScrapeTargets, STATUS_TARGETS } from "@workspace/config/scrape-targets";
import { describeMarketHandling } from "../providers";

const MARKET_DOCS_START = "{/* market-support:start — generated by `pnpm --filter @workspace/lib docs:markets` */}";
const MARKET_DOCS_END = "{/* market-support:end */}";

const SCRAPERS = [
	["cloro", "Cloro"],
	["brightdata", "BrightData"],
	["oxylabs", "Oxylabs"],
	["searchapi", "SearchApi"],
	["olostep", "Olostep"],
	["dataforseo", "DataForSEO"],
] as const;

const SURFACES = ["chatgpt", "google-ai-mode", "google-ai-overview", "gemini", "bing-ai-mode", "perplexity"];

const APIS = [
	["openai-api", "OpenAI API"],
	["anthropic-api", "Anthropic API"],
	["mistral-api", "Mistral API"],
	["openrouter", "OpenRouter"],
] as const;

const monitored = parseScrapeTargets(STATUS_TARGETS.join(","));

/** Past this many, a list of exceptions stops being readable in a table cell. */
const MAX_NAMED_EXCEPTIONS = 4;

const handlingIn = (target: ModelConfig, country: string) =>
	describeMarketHandling(target, { ...DEFAULT_MARKET, country });

function describeTarget(target: ModelConfig): string {
	const elsewhere = COUNTRIES.filter((country) => country.code !== DEFAULT_MARKET.country);
	const unsupported = elsewhere.filter((country) => handlingIn(target, country.code).country !== "localized");
	if (handlingIn(target, DEFAULT_MARKET.country).country === "location-free") return "No location";
	if (unsupported.length === elsewhere.length) return "Provider default";

	const language = handlingIn(target, DEFAULT_MARKET.country).sendsLanguage ? " + language" : "";
	if (unsupported.length === 0) return `Country${language}`;
	const exceptions =
		unsupported.length <= MAX_NAMED_EXCEPTIONS
			? unsupported.map((country) => country.name).join(", ")
			: `${unsupported.length} countries`;
	return `Country${language}, except ${exceptions}`;
}

function scraperCell(model: string, provider: string): string {
	const targets = monitored.filter((t) => t.model === model && t.provider === provider && t.webSearch);
	if (targets.length === 0) return "Not offered";
	const unpinned = targets.find((t) => !t.version);
	const pinned = targets.find((t) => t.version);
	const base = unpinned && describeTarget(unpinned);
	const pinnedCell = pinned && describeTarget(pinned);
	if (base && pinnedCell && base !== pinnedCell) return `${base} (${pinnedCell} with a pinned model)`;
	return base || `${pinnedCell} (pinned model only)`;
}

function apiCell(provider: string, webSearch: boolean): string {
	const cells = new Set(
		monitored.filter((t) => t.provider === provider && t.webSearch === webSearch).map(describeTarget),
	);
	return [...cells].join(" / ") || "Not offered";
}

const row = (cells: string[]) => `| ${cells.join(" | ")} |`;

function table(header: string[], rows: string[][]): string {
	return [row(header), row(header.map(() => "---")), ...rows.map(row)].join("\n");
}

function marketSupportMarkdown(): string {
	const scrapers = table(
		["Surface", ...SCRAPERS.map(([, name]) => name)],
		SURFACES.map((model) => [getModelMeta(model).label, ...SCRAPERS.map(([id]) => scraperCell(model, id))]),
	);
	const apis = table(
		["API", "With web search", "Without web search"],
		APIS.map(([id, name]) => [name, apiCell(id, true), apiCell(id, false)]),
	);
	const countries = table(
		["Country", "Code", "Languages offered"],
		COUNTRIES.map((country) => [
			country.name,
			`\`${country.code}\``,
			[...country.languages, "en"].map(languageName).join(", "),
		]),
	);
	const languages = table(
		["Language", "Code"],
		LANGUAGES.map((language) => [language.name, `\`${language.code}\``]),
	);
	return [
		MARKET_DOCS_START,
		"",
		"### What Each Provider Is Told",
		"",
		scrapers,
		"",
		apis,
		"",
		"### Countries",
		"",
		countries,
		"",
		"### Languages",
		"",
		languages,
		"",
		MARKET_DOCS_END,
	].join("\n");
}

export function withMarketSupport(mdx: string): string {
	const start = mdx.indexOf("{/* market-support:start");
	const end = mdx.indexOf(MARKET_DOCS_END);
	if (start === -1 || end === -1) throw new Error("market support markers not found");
	return mdx.slice(0, start) + marketSupportMarkdown() + mdx.slice(end + MARKET_DOCS_END.length);
}
